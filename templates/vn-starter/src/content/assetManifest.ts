import { speechRecordings } from "./speechRegistry";
import type { AssetManifest } from "./content.types";
export class AssetRegistry {
  constructor(private readonly manifest: AssetManifest) {}
  private resolve(group: keyof AssetManifest, id: string): string {
    const url = this.manifest[group]?.[id];
    if (!url) throw new Error(`Unknown ${group} asset: ${id}`);
    return url;
  }
  getBackground(id: string): string {
    return this.resolve("backgrounds", id);
  }
  backgroundEntries(): [string, string][] {
    return Object.entries(this.manifest.backgrounds);
  }
  getCharacter(id: string): string {
    return this.resolve("characters", id);
  }
  characterEntries(): [string, string][] {
    return Object.entries(this.manifest.characters);
  }
  getAudio(id: string): string {
    return this.resolve("audio", id);
  }
  getUi(id: string): string {
    return this.resolve("ui", id);
  }
  getProp(id: string): string {
    return this.resolve("props", id);
  }
}
